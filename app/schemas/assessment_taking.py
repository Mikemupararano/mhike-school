class AssessmentTakingResponseSave(BaseModel):
    """
    Autosave payload for one learner response.

    ``question_id`` is carried in the route rather than the payload.

    ``response_data`` remains a string at the ORM/service boundary because the
    existing AssessmentResponse column is Text. New clients may nevertheless
    submit structured dictionaries; diagram-annotation payloads are validated
    and serialised by the shared response-data normaliser.

    ``source_reference`` is intentionally absent from learner input. It is
    internal provenance metadata and must not be forgeable by a browser client.
    """

    model_config = ConfigDict(
        extra="forbid",
    )

    response_text: str | None = None
    response_data: str | None = None

    @field_validator(
        "response_data",
        mode="before",
    )
    @classmethod
    def validate_response_data(
        cls,
        value: Any,
    ) -> str | None:
        return _normalise_response_data(value)


class AssessmentTakingResponseOut(BaseModel):
    """
    Learner-safe representation of one saved response.

    Marking decisions, marks, marker comments, moderation information and
    internal source references are deliberately excluded.
    """

    model_config = ConfigDict(
        from_attributes=True,
    )

    id: int
    question_id: int

    status: AssessmentResponseStatus

    response_text: str | None = None
    response_data: str | None = None

    created_at: datetime
    updated_at: datetime
    submitted_at: datetime | None = None


