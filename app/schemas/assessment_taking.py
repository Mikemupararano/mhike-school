class StudentAssessmentSummaryOut(BaseModel):
    """
    One assessment allocation shown in the logged-in student's assessment list.

    The candidate record is resolved server-side from ``current_user.id``.
    Candidate IDs, candidate numbers, access-arrangement notes, storage metadata,
    marking data, and information about other candidates are not exposed.
    """

    assessment_id: int

    title: str
    description: str | None = None

    assessment_type: str | None = None
    academic_year: str | None = None
    term: str | None = None

    assessment_status: AssessmentStatus
    candidate_status: AssessmentCandidateStatus

    scheduled_at: datetime | None = None
    closes_at: datetime | None = None

    started_at: datetime | None = None
    submitted_at: datetime | None = None

    can_start: bool
    can_resume: bool
    is_submitted: bool


# ---------------------------------------------------------------------------
# Full learner attempt
# ---------------------------------------------------------------------------


class StudentAssessmentAttemptOut(BaseModel):
    """
    Full candidate-safe assessment-taking payload.

    The service supplies this only after:
        - active-user validation;
        - student-role validation;
        - candidate ownership validation;
        - school-scope validation;
        - assessment availability/lifecycle validation.

    The payload contains only the logged-in learner's own attempt state.
    """

    assessment_id: int

    title: str
    description: str | None = None

    assessment_type: str | None = None
    academic_year: str | None = None
    term: str | None = None

    assessment_status: AssessmentStatus
    candidate_status: AssessmentCandidateStatus

    scheduled_at: datetime | None = None
    closes_at: datetime | None = None

    started_at: datetime | None = None
    submitted_at: datetime | None = None

    script: AssessmentTakingScriptOut | None = None

    sections: list[AssessmentTakingSectionOut] = Field(
        default_factory=list,
    )

    questions: list[AssessmentTakingQuestionOut] = Field(
        default_factory=list,
    )

    responses: list[AssessmentTakingResponseOut] = Field(
        default_factory=list,
    )


class StudentAssessmentStartOut(StudentAssessmentAttemptOut):
    """
    Attempt payload returned after a learner starts or resumes an assessment.
    """

    message: str = "Assessment started."


class StudentAssessmentSubmitOut(BaseModel):
    """
    Confirmation returned after the learner submits the browser assessment.

    The submitted script and candidate are both transitioned atomically by the
    student-taking service. No marking information is exposed.
    """

    assessment_id: int

    candidate_status: AssessmentCandidateStatus
    script_status: AssessmentScriptStatus

    submitted_at: datetime

    message: str = "Assessment submitted."
