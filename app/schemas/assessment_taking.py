# ---------------------------------------------------------------------------
# Candidate-safe question content
# ---------------------------------------------------------------------------


class AssessmentTakingOptionOut(BaseModel):
    """
    Learner-safe structured answer option.

    Correctness and feedback are deliberately excluded.
    """

    model_config = ConfigDict(
        from_attributes=True,
    )

    id: int
    text: str
    order: int


class AssessmentTakingAssetOut(BaseModel):
    """
    Learner-safe question asset.

    Server-side storage paths, source-document identifiers, page coordinates,
    extraction provenance, and other internal metadata are deliberately
    excluded.

    ``content_url`` is an authorised API route generated by the endpoint/service
    layer. It is not persisted on AssessmentQuestionAsset.
    """

    id: int
    asset_type: AssessmentQuestionAssetType

    alt_text: str | None = None
    caption: str | None = None

    order: int

    content_url: str


class AssessmentTakingQuestionOut(BaseModel):
    """
    One learner-visible canonical assessment question.

    This schema deliberately excludes:
        - correct-option flags;
        - option feedback;
        - mark schemes;
        - marking decisions;
        - asset storage paths and extraction provenance.
    """

    model_config = ConfigDict(
        from_attributes=True,
    )

    id: int
    assessment_id: int

    section_id: int | None = None
    parent_question_id: int | None = None

    question_number: str

    title: str | None = None
    prompt: str | None = None

    question_type: AssessmentQuestionType

    maximum_mark: Decimal

    order: int
    is_markable: bool

    options: list[AssessmentTakingOptionOut] = Field(
        default_factory=list,
    )

    assets: list[AssessmentTakingAssetOut] = Field(
        default_factory=list,
    )


class AssessmentTakingSectionOut(BaseModel):
    """
    Learner-visible assessment section metadata.
    """

    model_config = ConfigDict(
        from_attributes=True,
    )

    id: int
    assessment_id: int

    title: str
    description: str | None = None

    order: int
    is_optional: bool


