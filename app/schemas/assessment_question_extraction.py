class AssessmentQuestionExtractionReviewStatus(StrEnum):
    """
    Teacher-review state for an extraction proposal.

    This is deliberately proposal-level state rather than an extraction-row
    status. The extraction itself remains COMPLETED until it is explicitly
    imported or otherwise superseded.
    """

    UNREVIEWED = "unreviewed"
    IN_PROGRESS = "in_progress"
    REVIEWED = "reviewed"


class AssessmentQuestionExtractionSource(BaseModel):
    """
    Source evidence identifying where a proposed question was detected.

    Source evidence is generated by the extractor and is never rewritten by a
    teacher review request.
    """

    model_config = ConfigDict(
        extra="allow",
    )

    page_number: int = Field(
        ge=1,
    )

    line_number: int | None = Field(
        default=None,
        ge=1,
    )

    source_line: str | None = None


class AssessmentQuestionExtractionOption(BaseModel):
    """
    One structured answer option proposed for a question.

    ``is_correct`` is teacher/authoring metadata. Candidate-facing assessment
    endpoints must never expose it.
    """

    model_config = ConfigDict(
        extra="allow",
    )

    text: str = Field(
        min_length=1,
        max_length=20_000,
    )

    order: int = Field(
        default=1,
        ge=1,
    )

    is_correct: bool = False

    feedback: str | None = Field(
        default=None,
        max_length=20_000,
    )


class AssessmentQuestionExtractionAsset(BaseModel):
    """
    One visual/resource proposed for a question.

    Extraction-owned provenance remains server-controlled. A detected asset may
    point at a generated crop through ``storage_path``. That path remains
    server-side storage metadata and is never accepted from a review request.

    ``content_url`` is derived by the API response layer and provides an
    authorised browser-facing route for displaying the asset. It is never
    persisted into proposal_data.

    ``source_bbox`` uses PDF/page coordinates and is kept with the proposal so
    the original location can be audited and, when needed, re-cropped.
    """

    model_config = ConfigDict(
        extra="allow",
    )

    asset_type: AssessmentQuestionAssetType = AssessmentQuestionAssetType.FIGURE

    storage_path: str | None = None

    content_url: str | None = None

    original_filename: str | None = Field(
        default=None,
        max_length=255,
    )

    mime_type: str | None = Field(
        default=None,
        max_length=255,
    )

    file_size_bytes: int | None = Field(
        default=None,
        ge=0,
    )

    alt_text: str | None = Field(
        default=None,
        max_length=20_000,
    )

    caption: str | None = Field(
        default=None,
        max_length=20_000,
    )

    order: int = Field(
        default=1,
        ge=1,
    )

    candidate_visible: bool = True

    source_document_id: int | None = Field(
        default=None,
        gt=0,
    )

    source_page_number: int | None = Field(
        default=None,
        gt=0,
    )

    source_bbox: dict[str, Any] | None = None

    included: bool = True

    reviewed: bool = False


class AssessmentQuestionExtractionCandidate(BaseModel):
    """
    One machine-detected question candidate awaiting teacher review.

    The candidate is deliberately separate from the canonical
    AssessmentQuestion model. Extraction alone never creates live questions.

    Teacher edits are persisted back into the proposal copy only. Raw page
    evidence remains unchanged.
    """

    model_config = ConfigDict(
        extra="allow",
    )

    question_number: str = Field(
        min_length=1,
    )

    text: str = ""

    marks: int | None = Field(
        default=None,
        ge=0,
    )

    depth: int = Field(
        default=0,
        ge=0,
    )

    parent_question_number: str | None = None

    question_type: AssessmentQuestionType = AssessmentQuestionType.WRITTEN

    options: list[AssessmentQuestionExtractionOption] = Field(
        default_factory=list,
    )

    assets: list[AssessmentQuestionExtractionAsset] = Field(
        default_factory=list,
    )

    included: bool = True

    source: AssessmentQuestionExtractionSource

    confidence: str = "candidate"

    requires_review: bool = True

    reviewed: bool = False


