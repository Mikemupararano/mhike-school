class AssessmentQuestionExtractionReviewQuestionUpdate(BaseModel):
    """
    Editable teacher-review fields for one proposal question.

    ``candidate_index`` identifies the existing proposal item. Source evidence,
    confidence metadata, and extractor evidence are intentionally absent from
    this request model so the client cannot replace them.
    """

    model_config = ConfigDict(
        extra="forbid",
    )

    candidate_index: int = Field(
        ge=0,
    )

    question_number: str = Field(
        min_length=1,
        max_length=100,
    )

    text: str = Field(
        default="",
        max_length=20_000,
    )

    marks: int | None = Field(
        default=None,
        ge=0,
        le=10_000,
    )

    parent_question_number: str | None = Field(
        default=None,
        max_length=100,
    )

    question_type: AssessmentQuestionType | None = None

    options: list[AssessmentQuestionExtractionOption] | None = None

    assets: list[AssessmentQuestionExtractionReviewAssetUpdate] | None = None

    included: bool = True

    @model_validator(
        mode="after",
    )
    def validate_collection_identity(
        self,
    ) -> AssessmentQuestionExtractionReviewQuestionUpdate:
        """
        Validate collection-local identities while permitting in-progress MCQ
        authoring.

        Full interaction rules are enforced only when the whole proposal is
        marked REVIEWED, so autosave can persist an option list while the
        teacher is still constructing it.
        """

        if self.options is not None:
            option_orders = [option.order for option in self.options]

            if len(option_orders) != len(set(option_orders)):
                raise ValueError(
                    "Question option order values must be unique.",
                )

        if self.assets is not None:
            asset_indexes = [asset.asset_index for asset in self.assets]

            if len(asset_indexes) != len(set(asset_indexes)):
                raise ValueError(
                    "Each asset_index may appear only once.",
                )

            asset_orders = [asset.order for asset in self.assets if asset.included]

            if len(asset_orders) != len(set(asset_orders)):
                raise ValueError(
                    "Included question asset order values must be unique.",
                )

        return self

    reviewed: bool = True


class AssessmentQuestionExtractionReviewUpdate(BaseModel):
    """
    Request used to save teacher edits to an extraction proposal.

    The request replaces the editable state of the proposal questions while
    preserving all machine-generated source evidence on the server.
    """

    model_config = ConfigDict(
        extra="forbid",
    )

    review_status: AssessmentQuestionExtractionReviewStatus = (
        AssessmentQuestionExtractionReviewStatus.IN_PROGRESS
    )

    review_notes: str | None = Field(
        default=None,
        max_length=10_000,
    )

    questions: list[AssessmentQuestionExtractionReviewQuestionUpdate] = Field(
        min_length=1,
    )

    @model_validator(
        mode="after",
    )
    def validate_candidate_indexes(
        self,
    ) -> AssessmentQuestionExtractionReviewUpdate:
        """
        Each original proposal candidate may appear at most once.
        """

        candidate_indexes = [question.candidate_index for question in self.questions]

        if len(candidate_indexes) != len(set(candidate_indexes)):
            raise ValueError("Each candidate_index may appear only once.")

        if self.review_status != AssessmentQuestionExtractionReviewStatus.REVIEWED:
            return self

        for question in self.questions:
            if not question.included:
                continue

            question_type = question.question_type or AssessmentQuestionType.WRITTEN

            options = question.options or []
            option_count = len(options)
            correct_count = sum(1 for option in options if option.is_correct)

            if (
                question_type
                in {
                    AssessmentQuestionType.WRITTEN,
                    AssessmentQuestionType.NUMERIC,
                    AssessmentQuestionType.DIAGRAM_ANNOTATION,
                    AssessmentQuestionType.STRUCTURAL,
                }
                and option_count > 0
            ):
                raise ValueError(
                    f"Question {question.question_number!r}: written, numeric, "
                    "diagram-annotation and structural questions cannot have "
                    "multiple-choice options.",
                )

            if question_type == AssessmentQuestionType.MULTIPLE_CHOICE_SINGLE:
                if option_count < 2:
                    raise ValueError(
                        f"Question {question.question_number!r}: a single-answer "
                        "multiple-choice question must have at least two options.",
                    )

                if correct_count != 1:
                    raise ValueError(
                        f"Question {question.question_number!r}: a single-answer "
                        "multiple-choice question must have exactly one correct "
                        "option.",
                    )

            if question_type == AssessmentQuestionType.MULTIPLE_CHOICE_MULTIPLE:
                if option_count < 2:
                    raise ValueError(
                        f"Question {question.question_number!r}: a multiple-answer "
                        "multiple-choice question must have at least two options.",
                    )

                if correct_count < 1:
                    raise ValueError(
                        f"Question {question.question_number!r}: a multiple-answer "
                        "multiple-choice question must have at least one correct "
                        "option.",
                    )

            if question_type == AssessmentQuestionType.TRUE_FALSE:
                if option_count != 2:
                    raise ValueError(
                        f"Question {question.question_number!r}: a true/false "
                        "question must have exactly two options.",
                    )

                if correct_count != 1:
                    raise ValueError(
                        f"Question {question.question_number!r}: a true/false "
                        "question must have exactly one correct option.",
                    )

            if question.assets is not None:
                unreviewed_assets = [
                    asset.asset_index
                    for asset in question.assets
                    if asset.included and not asset.reviewed
                ]

                if unreviewed_assets:
                    raise ValueError(
                        f"Question {question.question_number!r}: all included "
                        "visual assets must be reviewed before the proposal can "
                        "be marked reviewed.",
                    )

        return self


