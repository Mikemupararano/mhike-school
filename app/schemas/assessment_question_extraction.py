class AssessmentQuestionExtractionImportResponse(
    AssessmentQuestionExtractionResponse,
):
    """
    Response returned after explicit reviewed-proposal import.

    Import is a distinct action from extraction and review. The response
    therefore reports both the final extraction state and the canonical
    questions created by the atomic import transaction.
    """

    message: str = "Reviewed question extraction imported."

    imported_question_count: int = Field(
        ge=0,
    )

    imported_markable_question_count: int = Field(
        ge=0,
    )

    synthesised_parent_count: int = Field(
        ge=0,
    )

    imported_total_marks: Decimal = Field(
        ge=0,
    )

    imported_questions: list[AssessmentQuestionExtractionImportedQuestionResponse] = (
        Field(
            default_factory=list,
        )
    )


